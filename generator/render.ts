import path from 'node:path'
import type { ComponentCaseT, ElementQueryT, GeneratedTestPlan, Value } from './schema.js'

export const GENERATED_TEST_FILE_MARKER = '// Generated by Vitest AI Test Planner.'

function identifier(s: string): string {
  if (!/^[A-Za-z_$][\w$]*$/.test(s)) throw new Error(`Invalid identifier: ${s}`)
  return s
}
function value(v: Value): string {
  switch (v.kind) {
    case 'undefined': return 'undefined'
    case 'nan': return 'NaN'
    case 'infinity': return 'Infinity'
    case 'negative_infinity': return '-Infinity'
    case 'json': return JSON.stringify(JSON.parse(v.json))
  }
}
function quoted(s: string) { return JSON.stringify(s) }
function moduleName(p: string, sourceFile: string, targetFile: string) {
  if (!/^\.\.?\//.test(p) || p.includes('\\')) throw new Error(`Unsupported mock module path: ${p}`)
  const resolved = path.posix.join(path.posix.dirname(sourceFile), p.replace(/\.(ts|tsx|jsx)$/, '.js'))
  if (resolved.startsWith('..') || path.posix.isAbsolute(resolved)) throw new Error(`Mock module escapes repository: ${p}`)
  const relative = path.posix.relative(path.posix.dirname(targetFile), resolved)
  return relative.startsWith('.') ? relative : `./${relative}`
}
function elementCode(q: ElementQueryT, matcher: string): string {
  const name = q.name ? `, { name: ${quoted(q.name)}, hidden: true }` : q.by === 'role' ? ', { hidden: true }' : ''
  const query = matcher === 'toBeInTheDocument' ? 'queryBy' : 'getBy'
  switch (q.by) {
    case 'role': return `screen.${query}Role(${quoted(q.value)}${name})`
    case 'text': return `screen.${query}Text(${quoted(q.value)})`
    case 'label_text': return `screen.${query}LabelText(${quoted(q.value)})`
    case 'test_id': return `screen.${query}TestId(${quoted(q.value)})`
    case 'dialog': return `view.container.querySelector('dialog')!`
    case 'container': return 'view.container'
  }
}
function propName(s: string): string {
  if (!/^[A-Za-z_$][\w$-]*$/.test(s)) throw new Error(`Invalid prop name: ${s}`)
  return JSON.stringify(s)
}
function propsObject(props: { name: string; value: Value }[]): string {
  return `{ ${props.map(p => `${propName(p.name)}: ${value(p.value)}`).join(', ')} }`
}
function renderComponentCase(test: ComponentCaseT): string[] {
  const target = quoted(test.target_export)
  identifier(test.target_export)
  const spyNames = test.spy_props.map(identifier)
  if (new Set(spyNames).size !== spyNames.length) throw new Error(`Duplicate spy prop in ${test.name}`)
  for (const p of test.props) if (spyNames.includes(p.name)) throw new Error(`Prop ${p.name} is both a value and a spy in ${test.name}`)
  const lines = [`  it(${quoted(test.name)}, async () => {`, '    const user = userEvent.setup()']
  lines.push(`    const spies = { ${spyNames.map(n => `${n}: vi.fn()`).join(', ')} }`)
  lines.push(`    const baseProps = { ...${propsObject(test.props)}, ...spies }`)
  const children = test.children_text ? `, ${quoted(test.children_text)}` : ''
  lines.push(`    const ui = (props: Record<string, unknown>) => createElement(ThemeProvider, { theme }, createElement(subject[${target}] as any, props${children}))`)
  lines.push('    const view = render(ui(baseProps))')
  for (const step of test.steps) {
    if (step.action === 'rerender') {
      lines.push(`    view.rerender(ui({ ...baseProps, ...${propsObject(step.props)} }))`)
    } else if (step.action === 'click') {
      lines.push(`    await user.click(${elementCode(step.target, 'click')})`)
    } else if (step.action === 'type') {
      lines.push(`    await user.type(${elementCode(step.target, 'type')}, ${quoted(step.text)})`)
    } else {
      lines.push(`    fireEvent(${elementCode(step.target, 'cancel')}, new Event('cancel', { cancelable: true }))`)
    }
  }
  for (const a of test.assertions) {
    const negated = a.expected ? '' : '.not'
    const args = a.matcher_args.map(value).join(', ')
    if (a.target.kind === 'spy') {
      if (!spyNames.includes(a.target.prop)) throw new Error(`Assertion references unknown spy ${a.target.prop} in ${test.name}`)
      if (!a.matcher.startsWith('toHaveBeenCalled')) throw new Error(`Spy assertion needs a toHaveBeenCalled* matcher in ${test.name}`)
      lines.push(`    expect(spies.${a.target.prop})${negated}.${a.matcher}(${args})`)
    } else {
      if (a.matcher.startsWith('toHaveBeenCalled')) throw new Error(`Element assertion cannot use ${a.matcher} in ${test.name}`)
      lines.push(`    expect(${elementCode(a.target.query, a.matcher)})${negated}.${a.matcher}(${args})`)
    }
  }
  lines.push('  })', '')
  return lines
}

export function renderTestFile(plan: GeneratedTestPlan, sourceFile: string, targetFile: string): string {
  const sourceModule = sourceFile.replace(/\.(tsx?|jsx?)$/, '.js')
  const relativeModule = path.posix.relative(path.posix.dirname(targetFile), sourceModule)
  const base = relativeModule.startsWith('.') ? relativeModule : `./${relativeModule}`
  const hasComponents = plan.component_cases.length > 0
  if (hasComponents && !targetFile.startsWith('frontend/')) throw new Error('Component cases are only supported for frontend files')
  const themeModule = path.posix.relative(path.posix.dirname(targetFile), 'frontend/src/design-system/theme/theme.js')
  const themeImport = themeModule.startsWith('.') ? themeModule : `./${themeModule}`
  const mockPaths = [...new Set(plan.cases.flatMap(c => c.mock_function.map(m => moduleName(m.module_path, sourceFile, targetFile))))].sort()
  const importLines = mockPaths.map((p, i) => `import * as dependency${i} from ${quoted(p)}`)
  const lines = [
    `${GENERATED_TEST_FILE_MARKER} Review assertions before merging.`,
    `import { describe, it, expect, vi, afterEach${hasComponents ? ', beforeAll' : ''} } from 'vitest'`,
    ...(hasComponents ? [
      `import { createElement } from 'react'`,
      `import { fireEvent, render, screen } from '@testing-library/react'`,
      `import userEvent from '@testing-library/user-event'`,
      `import { ThemeProvider } from 'styled-components'`,
      `import { theme } from ${quoted(themeImport)}`,
    ] : []),
    `import * as subject from ${quoted(base)}`,
    ...importLines,
    '',
    'afterEach(() => vi.restoreAllMocks())',
    '',
    ...(hasComponents ? [
      '// jsdom may not implement the native <dialog> modal API.',
      'beforeAll(() => {',
      '  const proto = HTMLDialogElement.prototype',
      '  if (!proto.showModal) {',
      "    proto.showModal = function (this: HTMLDialogElement) { this.setAttribute('open', '') }",
      "    proto.close = function (this: HTMLDialogElement) { this.removeAttribute('open') }",
      '  }',
      '})',
      '',
    ] : []),
    `describe(${quoted(plan.describe_name)}, () => {`,
  ]
  for (const test of plan.component_cases) lines.push(...renderComponentCase(test))
  for (const test of plan.cases) {
    const target = identifier(test.target_export)
    if (!test.testing_stack.length) throw new Error(`No assertions in ${test.name}`)
    lines.push(`  it(${quoted(test.name)}, async () => {`)
    for (const mock of test.mock_function) {
      const idx = mockPaths.indexOf(moduleName(mock.module_path, sourceFile, targetFile))
      const method = {return:'mockReturnValue',resolve:'mockResolvedValue',reject:'mockRejectedValue',throw:'mockImplementation'}[mock.behavior]
      const args = mock.behavior === 'throw' ? `() => { throw new Error(String(${value(mock.value)})) }` : value(mock.value)
      lines.push(`    vi.spyOn(dependency${idx}, ${quoted(identifier(mock.export_name))}).${method}(${args})`)
    }
    const args = test.input_data.map(value).join(', ')
    const callee = `subject[${quoted(target)}]`
    const invocation = test.invocation === 'constructor' ? `new (${callee} as any)(${args})` : `(${callee} as any)(${args})`
    if (test.async_mode === 'sync') {
      if (test.testing_stack.some(s => s.matcher === 'toThrow')) {
        lines.push(`    const result = () => ${invocation}`)
      } else {
        lines.push(`    const result = ${invocation}`)
      }
    } else if (test.async_mode === 'rejects') {
      lines.push(`    const result = await ${invocation}.then(() => { throw new Error('Expected rejection') }, (error: unknown) => error instanceof Error ? error.message : error)`)
    } else {
      lines.push(`    const result = await ${invocation}`)
    }
    for (const assertion of test.testing_stack) {
      const negated = assertion.expected ? '' : '.not'
      const argValues = assertion.matcher_args.length ? assertion.matcher_args.map(value) :
        ['toBe', 'toEqual', 'toStrictEqual', 'toContain'].includes(assertion.matcher) ? [value(test.expected_output)] : []
      // A toThrow test must not execute the code before assertion.
      if (assertion.matcher === 'toThrow' && test.async_mode !== 'sync') throw new Error('toThrow only supports sync invocation')
      lines.push(`    expect(result)${negated}.${assertion.matcher}(${argValues.join(', ')})`)
    }
    lines.push('  })', '')
  }
  lines.push('})', '')
  return lines.join('\n')
}

export function testFilePath(source: string): string {
  const normalized = source.replace(/\\/g, '/')
  const backendPrefix = 'backend/src/'
  if (normalized.startsWith(backendPrefix)) {
    const relative = normalized.slice(backendPrefix.length)
    const ext = path.posix.extname(relative)
    const testExt = ext === '.tsx' || ext === '.jsx' ? '.ts' : ext
    return `backend/tests/${relative.slice(0, -ext.length)}.test${testExt}`
  }
  const ext = path.posix.extname(normalized)
  return normalized.slice(0, -ext.length) + '.test' + ext
}
