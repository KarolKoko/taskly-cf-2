import path from 'node:path'
import type { GeneratedTestPlan, Value } from './schema.js'

export const GENERATED_TEST_FILE_MARKER = '// Generated by Vitest AI Test Planner.'

function identifier(s: string): string {
  if (!/^[A-Za-z_$][\w$]*$/.test(s)) throw new Error(`Invalid identifier: ${s}`)
  return s
}
function value(v: Value): string {
  switch (v.kind) {
    case 'undefined': return 'undefined'
    case 'nan': return 'NaN'
    case 'infinity': return 'Infinity'
    case 'negative_infinity': return '-Infinity'
    case 'json': return JSON.stringify(JSON.parse(v.json))
  }
}
function quoted(s: string) { return JSON.stringify(s) }
function moduleName(p: string) {
  if (!/^\.\.?\//.test(p) || p.includes('\\') || p.split('/').includes('..')) throw new Error(`Unsupported mock module path: ${p}`)
  return p.replace(/\.(ts|tsx|jsx)$/, '.js')
}
export function renderTestFile(plan: GeneratedTestPlan, sourceFile: string, targetFile: string): string {
  const sourceModule = sourceFile.replace(/\.(tsx?|jsx?)$/, '.js')
  const relativeModule = path.posix.relative(path.posix.dirname(targetFile), sourceModule)
  const base = relativeModule.startsWith('.') ? relativeModule : `./${relativeModule}`
  const mockPaths = [...new Set(plan.cases.flatMap(c => c.mock_function.map(m => moduleName(m.module_path))))].sort()
  const importLines = mockPaths.map((p, i) => `import * as dependency${i} from ${quoted(p)}`)
  const lines = [
    `${GENERATED_TEST_FILE_MARKER} Review assertions before merging.`,
    `import { describe, it, expect, vi, afterEach } from 'vitest'`,
    `import * as subject from ${quoted(base)}`,
    ...importLines,
    '',
    'afterEach(() => vi.restoreAllMocks())',
    '',
    `describe(${quoted(plan.describe_name)}, () => {`,
  ]
  for (const test of plan.cases) {
    const target = identifier(test.target_export)
    if (!test.testing_stack.length) throw new Error(`No assertions in ${test.name}`)
    lines.push(`  it(${quoted(test.name)}, async () => {`)
    for (const mock of test.mock_function) {
      const idx = mockPaths.indexOf(moduleName(mock.module_path))
      const method = {return:'mockReturnValue',resolve:'mockResolvedValue',reject:'mockRejectedValue',throw:'mockImplementation'}[mock.behavior]
      const args = mock.behavior === 'throw' ? `() => { throw new Error(String(${value(mock.value)})) }` : value(mock.value)
      lines.push(`    vi.spyOn(dependency${idx}, ${quoted(identifier(mock.export_name))}).${method}(${args})`)
    }
    const args = test.input_data.map(value).join(', ')
    const callee = `subject[${quoted(target)}]`
    const invocation = test.invocation === 'constructor' ? `new (${callee} as any)(${args})` : `(${callee} as any)(${args})`
    if (test.async_mode === 'sync') {
      if (test.testing_stack.some(s => s.matcher === 'toThrow')) {
        lines.push(`    const result = () => ${invocation}`)
      } else {
        lines.push(`    const result = ${invocation}`)
      }
    } else if (test.async_mode === 'rejects') {
      lines.push(`    const result = await ${invocation}.then(() => { throw new Error('Expected rejection') }, (error: unknown) => error)`)
    } else {
      lines.push(`    const result = await ${invocation}`)
    }
    for (const assertion of test.testing_stack) {
      const negated = assertion.expected ? '' : '.not'
      const argValues = assertion.matcher_args.length ? assertion.matcher_args.map(value) :
        ['toBe', 'toEqual', 'toStrictEqual', 'toContain'].includes(assertion.matcher) ? [value(test.expected_output)] : []
      // A toThrow test must not execute the code before assertion.
      if (assertion.matcher === 'toThrow' && test.async_mode !== 'sync') throw new Error('toThrow only supports sync invocation')
      lines.push(`    expect(result)${negated}.${assertion.matcher}(${argValues.join(', ')})`)
    }
    lines.push('  })', '')
  }
  lines.push('})', '')
  return lines.join('\n')
}

export function testFilePath(source: string): string {
  const normalized = source.replace(/\\/g, '/')
  const backendPrefix = 'backend/src/'
  if (normalized.startsWith(backendPrefix)) {
    const relative = normalized.slice(backendPrefix.length)
    const ext = path.posix.extname(relative)
    const testExt = ext === '.tsx' || ext === '.jsx' ? '.ts' : ext
    return `backend/tests/${relative.slice(0, -ext.length)}.test${testExt}`
  }
  const ext = path.posix.extname(normalized)
  return normalized.slice(0, -ext.length) + '.test' + ext
}
