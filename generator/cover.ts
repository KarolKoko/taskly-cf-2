import { readdir, readFile } from 'node:fs/promises'
import path from 'node:path'
import type { ChangedFile } from './diff.js'
import { GENERATED_TEST_FILE_MARKER } from './render.js'

const ROOTS = ['frontend/src', 'backend/src']
const SKIPPED_DIRS = new Set(['node_modules', 'generated', 'dist', 'coverage', '__mocks__', 'test', 'tests'])
const SKIPPED_FILE = /(\.(test|spec|stories|styles|types|variants)\.[jt]sx?$)|(\.d\.ts$)|(^|\/)(index|main|mocks|types|GlobalStyles)\.[jt]sx?$|(^|\/)(vite|vitest)\.config\./
const SOURCE_FILE = /\.(tsx?|jsx?)$/
const IMPORT_SPECIFIER = /(?:from|import)\s*\(?\s*['"](\.{1,2}\/[^'"]+)['"]/g

async function walk(dir: string, out: string[] = []): Promise<string[]> {
  let entries
  try { entries = await readdir(dir, { withFileTypes: true }) }
  catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return out
    throw error
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!SKIPPED_DIRS.has(entry.name)) await walk(path.join(dir, entry.name), out)
    } else out.push(path.join(dir, entry.name))
  }
  return out
}

const posix = (p: string) => p.split(path.sep).join('/')
const stem = (p: string) => p.replace(/\.(tsx?|jsx?)$/, '').replace(/\.js$/, '')

/** Source modules that any existing test file already imports, resolved to repo-relative stems. */
async function importedByTests(repo: string, files: string[]): Promise<Set<string>> {
  const covered = new Set<string>()
  for (const file of files.filter(f => /\.(test|spec)\.[jt]sx?$/.test(f))) {
    const text = await readFile(file, 'utf8')
    // Agent-generated tests are regenerated by a coverage run, so they do not count as coverage.
    if (text.startsWith(GENERATED_TEST_FILE_MARKER)) continue
    for (const match of text.matchAll(IMPORT_SPECIFIER)) {
      const resolved = path.resolve(path.dirname(file), match[1])
      covered.add(stem(posix(path.relative(repo, resolved))))
    }
    // A colocated test is the primary subject of its sibling source file.
    covered.add(stem(posix(path.relative(repo, file)).replace(/\.(test|spec)(?=\.[jt]sx?$)/, '')))
  }
  return covered
}

export interface CoverageTarget extends ChangedFile { reason: string }

/**
 * Lists source files with no test importing them. Files that already have a developer-authored
 * test are never returned, so a coverage run only creates or refreshes generated tests.
 */
export async function findCoverageTargets(repo: string): Promise<CoverageTarget[]> {
  const files = (await Promise.all(ROOTS.map(root => walk(path.join(repo, root))))).flat()
  const backendTests = await walk(path.join(repo, 'backend/tests'))
  const covered = await importedByTests(repo, [...files, ...backendTests])
  const targets: CoverageTarget[] = []
  for (const file of files.sort()) {
    const relative = posix(path.relative(repo, file))
    if (!SOURCE_FILE.test(relative) || SKIPPED_FILE.test(relative)) continue
    if (covered.has(stem(relative))) continue
    targets.push({
      file: relative,
      addedLines: [],
      patch: `Full-file coverage run: no diff is available. Treat the whole file as changed behavior and cover its exported business logic.\n`,
      reason: 'No test imports this module',
    })
  }
  return targets
}

export function coverRunEnabled(env: NodeJS.ProcessEnv = process.env): boolean {
  return /^(1|true|yes)$/i.test(env.COVER_RUN?.trim() ?? '')
}
